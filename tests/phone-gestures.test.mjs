import assert from 'node:assert/strict';
import {build} from 'esbuild';
import {mkdtemp} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {parseHTML} from 'linkedom';
const {window}=parseHTML('<html><head><meta name="viewport" content="width=device-width, initial-scale=1.0"></head><body></body></html>');
Object.assign(globalThis,{window,document:window.document});
const dir=await mkdtemp(tmpdir()+'/sommni-gestures-');
await build({entryPoints:['src/phone-gestures.ts'],bundle:true,format:'esm',platform:'node',outfile:dir+'/test.mjs'});
const {initPhoneGestures}=await import(dir+'/test.mjs');
initPhoneGestures();assert.equal(document.documentElement.classList.contains('even-phone-gestures'),false);
assert.doesNotMatch(document.querySelector('meta').content||'',/user-scalable=no/);
window.flutter_inappwebview={callHandler(){}};initPhoneGestures();initPhoneGestures();
assert(document.documentElement.classList.contains('even-phone-gestures'));
assert.match(document.querySelector('meta').content,/maximum-scale=1.0/);
const touch=(name,count)=>{const event=new window.Event(name,{bubbles:true,cancelable:true});event.touches=Array(count).fill({});document.dispatchEvent(event);return event;};
assert.equal(touch('touchstart',1).defaultPrevented,false);
assert.equal(touch('touchmove',1).defaultPrevented,false);
assert.equal(touch('touchstart',2).defaultPrevented,true);
assert.equal(touch('touchmove',2).defaultPrevented,true);
const gesture=new window.Event('gesturestart',{cancelable:true});document.dispatchEvent(gesture);assert.equal(gesture.defaultPrevented,true);
console.log('PASS: zoom unchanged in regular browsers; Even pinch prevented, one-finger scrolling retained, initialization idempotent.');
