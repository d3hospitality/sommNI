import assert from 'node:assert/strict';
import {ReadingFollower,readingWords} from '../src/reading/alignment.ts';
const make=text=>new ReadingFollower([{label:'Notes',text}]);
let f=make('Deep ruby colour. Ripe black cherry and plum. Firm tannins with a long finish.');
assert.equal(f.hear('deep ruby','1'),2);
assert.equal(f.hear('deep ruby colour','1'),3);
assert.equal(f.hear('deep ruby colour','1'),3);
assert.equal(f.hear('please turn on the kitchen lights','2'),3);
assert.equal(f.hear('ripe black cherry and plum','3'),8);
assert.equal(f.hear('firm tannins with a long finish','4'),14);assert.ok(f.done);
f=make('Château Margaux and Grüner Veltliner. Fresh acidity with citrus aromas.');
assert.equal(f.hear('chateau margaux and gruner veltliner','1'),5);
assert.equal(f.hear('fresh acidity with citrus aromas','2'),10);assert.ok(f.done);
f=make('Fresh acidity and bright fruit. Fresh acidity and fine texture.');
assert.equal(f.hear('fresh acidity','1'),2);
assert.equal(f.hear('fresh acidity','2'),2,'repetition must not jump to second phrase');
assert.equal(f.hear('fresh acidity and bright fruit','2'),5);
assert.equal(f.hear('fresh acidity and fine texture','3'),10);
f=make('Appearance deep ruby colour. Aroma black cherry and plum. Palate firm tannins.');
assert.equal(f.hear('deep ruby colour','1'),4,'section labels may be skipped');
assert.equal(f.hear('black cherry and plum','2'),9);
f.seek(10);assert.equal(f.hear('firm tannins','3'),12);assert.ok(f.done);
f=make('A wine with crisp acidity. Later we discuss its history.');
assert.equal(f.hear('the','1'),0);assert.equal(f.hear('we talk about architecture and a meal','2'),0);
f=make('Dark cherries with silky tannins and a lingering finish.');
assert.equal(f.hear('dark cherriez with silky tannins','1'),5,'small transcription typo');
assert.equal(readingWords([{label:'',text:'Grüner, Château. 2022.'}]).length,3);
f=make('Ripe cherry and plum.');f.hear('ripe cherry and','1');assert.equal(f.hear('plum','2'),4,'a separate final word completes the passage');
console.log('Reading alignment assertions passed.');
