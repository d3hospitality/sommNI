// Build the server-side lookup indexes used to resolve uploaded wines (wine lists, scans, manual adds).
//
//   node --experimental-strip-types scripts/build-wine-index.mjs          # check the committed files are current
//   node --experimental-strip-types scripts/build-wine-index.mjs --write  # regenerate them
//
// shared/catalog-index.json : the 215 catalog wines (canonical ID, title, producer, place, grape, style)
// shared/place-index.json   : globe countries, winerymap winery clusters and the catalog region links
// Sources: src/constants.ts, src/data/catalog-identity.json, public/atlas/atlas-data.json,
// src/data/atlas-region-links.json. Nothing here is invented: aliases live in shared/region-aliases.json.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const read = f => JSON.parse(fs.readFileSync(path.join(root, f), 'utf8'));
const C = await import(path.join(root, 'src/constants.ts'));
const identity = read('src/data/catalog-identity.json');
const atlas = read('public/atlas/atlas-data.json');
const links = read('src/data/atlas-region-links.json').links;

const byKey = new Map(identity.entries.filter(e => e.status === 'active').map(e => [e.key, e.id]));
const wines = [];
for (const type of C.WINE_TYPES) for (const country of C.COUNTRIES[type]) for (const w of C.WINES[type]?.[country] || []) {
  const id = byKey.get(`${type}|${country}|${w.name}`);
  if (!id) continue;
  const at = w.name.lastIndexOf(' – ');
  wines.push({ id, title: at > 0 ? w.name.slice(0, at).trim() : w.name, producer: at > 0 ? w.name.slice(at + 3).trim() : '', type, country, region: w.region, grape: w.grape, style: w.style });
}
wines.sort((a, b) => a.id.localeCompare(b.id));

const places = {
  about: 'Generated by scripts/build-wine-index.mjs. countries: [ISO3, name]; clusters: winerymap winery clusters [name, ISO3, id]; links: catalog regions → cluster names.',
  countries: atlas.countries.map(c => [c.code, c.name]).sort((a, b) => a[0].localeCompare(b[0])),
  clusters: atlas.regions.map(r => [r.name, r.country, r.id]).sort((a, b) => a[1].localeCompare(b[1]) || a[0].localeCompare(b[0])),
  links: links.map(l => [l.region, l.clusters]).sort((a, b) => a[0].localeCompare(b[0])),
};
const outputs = { 'shared/catalog-index.json': { about: 'Generated by scripts/build-wine-index.mjs from the bundled catalog.', wines }, 'shared/place-index.json': places };
let stale = 0;
for (const [file, data] of Object.entries(outputs)) {
  const text = JSON.stringify(data) + '\n', target = path.join(root, file);
  const current = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : '';
  if (current === text) { console.log(`ok ${file}`); continue; }
  if (process.argv.includes('--write')) { fs.writeFileSync(target, text); console.log(`wrote ${file} (${(text.length / 1024).toFixed(0)} KB)`); }
  else { console.error(`STALE ${file}: run with --write`); stale++; }
}
console.log(JSON.stringify({ catalogWines: wines.length, countries: places.countries.length, clusters: places.clusters.length, links: places.links.length }));
process.exitCode = stale ? 1 : 0;
